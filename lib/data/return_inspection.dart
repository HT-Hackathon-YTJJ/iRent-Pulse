/// One frame the driver has to hand in, in strip order (Figma 拍照流程).
///
/// Seven slots, not five: the board opens on the 加油卡/停車卡 shot, takes both
/// cabin rows, and only then walks the four body corners. The order here *is*
/// the order of the strip and of the flow, so nothing else has to restate it.
///
/// The four corners go 左前 → 右前 → 右後 → 左後, which is one lap of the car:
/// across the nose, down the passenger side, across the tail. They used to go
/// 右前 → 左前 → 右後 → 左後, and that is two laps — the driver crossed the
/// front, came back, crossed to the rear-right, and crossed again. Four shots
/// is few enough that the wasted walking is the whole difference between a
/// return that feels like a circuit and one that feels like errands.
/// What the viewfinder draws over the live frame for one slot.
enum GuideStyle {
  /// Nothing. The driver frames the shot themselves.
  ///
  /// The two cabin rows. There is no repeatable angle to ask for inside a car
  /// — the phone is a hand's width from the seat back and every driver's
  /// posture puts it somewhere different — so an outline there is a shape
  /// nobody can match, and being unable to match it is the only thing it
  /// communicates. The strip tile still shows the 示意圖: saying *which* seats
  /// to point at is useful, drawing where their edges must land is not.
  none,

  /// The car render, tinted by [AimState]. The four body corners.
  silhouette,

  /// The 遮陽板 card holder: an outer frame with the two card pockets marked.
  ///
  /// Drawn rather than an asset — it is three rounded rectangles and two
  /// labels, which vector code renders crisply at any size and a PNG does not.
  cardPouch,
}

enum CaptureSpot {
  fuelCard(
    label: '加油卡/停車卡',
    screenTitle: '加油卡/停車卡',
    instruction: '於駕駛座上方的遮陽板',
    art: 'fuel_card',
    // The 遮陽板 card holder itself, not a card. Measured off the pouch: two
    // card pockets either side of the branded centre panel.
    guideAspect: 1.70,
    isCorner: false,
    guide: GuideStyle.cardPouch,
  ),
  interiorFront(
    label: '前座',
    screenTitle: '車內裝(前座)',
    instruction: '請拍攝前座照片',
    art: 'indoor_front',
    guideAspect: 1.6000,
    isCorner: false,
    guide: GuideStyle.none,
  ),
  interiorRear(
    label: '後座',
    screenTitle: '車內裝(後座)',
    instruction: '請拍攝後座照片',
    art: 'indoor_back',
    guideAspect: 1.5335,
    isCorner: false,
    guide: GuideStyle.none,
  ),
  frontLeft(
    label: '左前',
    art: 'left_front',
    guideAspect: 1.8804,
    guideBleed: 0.16,
  ),
  frontRight(
    label: '右前',
    art: 'right_front',
    guideAspect: 1.8955,
    guideBleed: -0.16,
  ),
  rearRight(
    label: '右後',
    art: 'right_back',
    guideAspect: 1.8054,
    guideBleed: 0.16,
  ),
  rearLeft(
    label: '左後',
    art: 'left_back',
    guideAspect: 1.8020,
    guideBleed: -0.16,
  );

  const CaptureSpot({
    required this.label,
    required this.art,
    required this.guideAspect,
    this.screenTitle = '車身拍照',
    this.instruction = '請拍攝車輛四角（含車牌）',
    this.isCorner = true,
    this.guide = GuideStyle.silhouette,
    this.guideBleed = 0,
  });

  /// Short name used inside the copy ("**右後** 照片有不明亮點…").
  final String label;

  /// Header title. The four body shots share one 車身拍照 task; the other three
  /// each name themselves.
  final String screenTitle;

  /// Sub-header under the title.
  final String instruction;

  /// Base name of the artwork this slot owns — strip tile and the three guide
  /// layers — all generated by `tool/gen_slot_assets.py` from the 1440px
  /// masters in `tool/slot_paint/`.
  final String art;

  /// Width ÷ height of the shape drawn over the frame. For a
  /// [GuideStyle.silhouette] slot it is measured off the source alpha by
  /// `gen_slot_assets.py`, so the viewfinder can lay the guide out without
  /// decoding the image first; for [GuideStyle.cardPouch] it is the pouch's
  /// own proportions. Unused when [guide] is [GuideStyle.none].
  final double guideAspect;

  /// True for the four body corners — the only slots the car detector, and so
  /// the guide-overlap check, can say anything about.
  final bool isCorner;

  /// What, if anything, is drawn over the live frame for this slot.
  final GuideStyle guide;

  /// A standing loosening of the aim thresholds for this slot, 0…1.
  ///
  /// The three interior shots get 0.35. The thresholds' defaults are tuned for
  /// a whole car at arm's length in daylight; the 遮陽板 and the two cabin rows
  /// are close-ups of dark surfaces under a roof, often with the driver's own
  /// shadow across them, and the blur floor and exposure ceilings that are
  /// right outdoors are simply not reachable in there. A slot that can never
  /// go green is a slot the driver fights until they abandon the return.
  double get aimSlack => isCorner ? 0 : 0.35;

  /// How far the silhouette is allowed to run off one edge of the screen, as a
  /// fraction of its own width. Negative bleeds off the **left** edge, positive
  /// off the right; 0 keeps the whole shape on screen.
  ///
  /// A guide that fits entirely on screen asks the driver to frame the *whole
  /// car*, which puts them ten paces back and makes the corner they are
  /// actually documenting — bumper, headlight, wheel arch — a handful of
  /// pixels wide. Letting the far end of the car run out of frame is what buys
  /// those pixels: the near corner grows to fill the screen, and the features
  /// the driver aligns against (front bumper line, A-pillar, wheel arch) are
  /// the ones that stay in it.
  ///
  /// So the bleed is always on the side **away from the corner being shot**,
  /// and it alternates down the strip because the walk does. In the 右前 render
  /// the nose sits on the right of the frame, so the tail is what runs off the
  /// left; 左前 is its mirror. The two rear shots follow the same rule one lap
  /// later — 右後 bleeds off the right and keeps its left margin, 左後 the
  /// mirror of that — which is what makes their outlines as large as the front
  /// pair's instead of a shrunken whole car floating in the middle of the
  /// frame.
  final double guideBleed;

  /// Strip indicator shown while the slot is still empty. 288×288 — 4x the
  /// 72pt tile, so it stays sharp on a 3x screen. It used to be the design
  /// repo's own 72×72 export, which was exactly one logical pixel per point
  /// and visibly mushy on a real phone.
  String get slotIcon => '$_kAssetRoot/slots/$art.png';

  /// Alignment silhouette laid over the live frame. White with a soft alpha
  /// edge, tinted per [AimState] at paint time.
  String get guideAsset => '$_kAssetRoot/guide/$art.png';

  /// The 示意圖 itself — the car render, drawn semi-transparent over the live
  /// frame underneath [guideEdgeAsset].
  ///
  /// A flat tinted silhouette can only say "the car goes roughly here". What
  /// the driver is being asked for is a *repeatable* angle, and repeatable
  /// means lining real features up against drawn ones: the bumper's lower
  /// edge, the A-pillar, where the wheel arch meets the sill. Those only exist
  /// in the render, so the render is what goes on screen.
  String get guideArtAsset => '$_kAssetRoot/guide/${art}_art.png';

  /// The same silhouette as an outline, drawn over [guideAsset]. Registered
  /// pixel for pixel with it, so both go in the same rect.
  String get guideEdgeAsset => '$_kAssetRoot/guide/${art}_edge.png';

  /// Live view behind the viewfinder chrome. A still stands in for the camera
  /// feed on a device that has none.
  String get viewfinderAsset => isCorner
      ? '$_kAssetRoot/camera_scene.png'
      : '$_kAssetRoot/shot_interior.jpg';

  /// Stand-in for the strip when a slot was "shot" without a camera behind it —
  /// a desktop, the web, a widget test. With a camera the tile shows the frame
  /// that was actually taken and this is never reached.
  String get shotAsset => isCorner
      ? '$_kAssetRoot/shot_scene.jpg'
      : '$_kAssetRoot/shot_interior.jpg';
}

/// What the on-device check makes of the current frame.
///
/// This is the 防亂拍 signal: it is evaluated live while the viewfinder is
/// open, never after the fact. The shutter stays armed in every state — an
/// off-target frame is warned about, not blocked (Figma scenario ⑥).
enum AimState {
  /// 未對準 — nothing recognisable in frame, or the car is nowhere near the
  /// outline. Grey.
  off(
    '未對準',
    AppColor.aimOff,
    AppColor.guideOff,
    AppColor.guideOffEdge,
    '對齊輪廓線',
  ),

  /// 接近 — the car is on the outline but at the wrong distance (or the frame
  /// is soft or badly lit). Amber, and the hint always says which way to walk.
  near('接近', AppColor.aimNear, AppColor.aimNear, AppColor.aimNear, '再靠近一點'),

  /// 已對準 — good enough to submit.
  locked(
    '已對準',
    AppColor.aimLocked,
    AppColor.aimLocked,
    AppColor.aimLocked,
    null,
  ),

  /// 車輛不符 — a plate was read, repeatedly and clearly, and it is not the car
  /// on the rental agreement. Red.
  ///
  /// Its own state rather than a flavour of [off] because it is the one verdict
  /// the driver cannot answer by moving the phone. Every other state means
  /// "adjust the shot"; this one means "you are standing at the wrong car", and
  /// a grey 未對準 badge would send them shuffling back and forth in front of
  /// somebody else's bumper. It still does not lock the shutter — see
  /// [AimVerdict.isAcceptable].
  wrongCar(
    '車輛不符',
    AppColor.aimWrongCar,
    AppColor.aimWrongCar,
    AppColor.aimWrongCar,
    '這不是你租的車',
  );

  const AimState(
    this.label,
    this.color,
    this.guideColor,
    this.guideEdgeColor,
    this.hint,
  );

  final String label;

  /// Badge fill under the header.
  final Color color;

  /// Fill of the alignment silhouette, and the tint of its outline.
  /// **灰 = 未對準・黃 = 距離不對・綠 = 已對準**, which is the only thing on screen
  /// that reads at arm's length while the driver is moving.
  final Color guideColor;

  /// Stroke around that silhouette. Same colour as the fill once the check is
  /// saying something (amber, green); a darker grey while it is not, because
  /// 未對準 is the one state that has to stand off a bright wall.
  final Color guideEdgeColor;

  /// Centre pill copy; null once the frame is good, when the pill disappears.
  final String? hint;

  bool get isAcceptable => this == AimState.locked;
}

