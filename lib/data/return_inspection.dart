/// The six columns of the Figma board, in board order — plus the live one.
enum ReturnScenario {
  /// ⓪ 真實檢測 — no script at all: the phone's camera drives L0, the photos go
  /// to L1, and L2/L3 run once the driver leaves. Selected automatically when
  /// the `api/` service answers, so a dead network falls back to the board
  /// rather than to a broken demo.
  live(number: '⓪', title: '真實 AI 檢測', caption: '相機跑 L0，照片送 L1，離開後跑 L2／L3。'),

  /// ① 一切順利（最常見）— 全程放行
  allClear(number: '①', title: '一切順利', caption: '拍照全達標，分析全過，直接放行，事後零通知。'),

  /// ② 局部反光・需重拍 — 唯一會擋下的照片問題
  glare(number: '②', title: '有一張需要重拍', caption: '右後照片反光影響判讀，補拍一張後放行。'),

  /// ③ 車內偵測到垃圾（整潔度）— 唯一強制處理點
  trash(number: '③', title: '車內偵測到垃圾', caption: '可清理後重拍，或接受信用影響直接還車。'),

  /// ④ 紀錄外損傷・輕微 — 使用者全程無感
  minorDamage(
    number: '④',
    title: '輕微損傷（無感放行）',
    caption: '畫面與情境①相同，差異只在事後一則好消息。',
  ),

  /// ⑤ 紀錄外損傷・嚴重 — 當下放行・事後人工
  severeDamage(number: '⑤', title: '嚴重損傷（求償）', caption: '放行頁一字不提，求償由客服人工聯繫。'),

  /// ⑥ 亂拍・自負責任送出 — 還車不阻斷
  sloppy(number: '⑥', title: '亂拍・自負責任送出', caption: '快門永不鎖定，不合格照片可直接送出。'),

  /// ⑦ 兩個問題同時發生 — 需處理頁一次列完、一次重拍
  multiple(
    number: '⑦',
    title: '同時有兩個問題',
    caption: '後座有垃圾＋右後反光，一頁列完，一次重拍兩張。',
  );

  const ReturnScenario({
    required this.number,
    required this.title,
    required this.caption,
  });

  final String number;
  final String title;
  final String caption;

  /// What the 還車分析 page reports for this scenario.
  ReturnAnalysis get analysis => switch (this) {
    ReturnScenario.glare => ReturnAnalysis.glare,
    ReturnScenario.trash => ReturnAnalysis.trash,
    ReturnScenario.multiple => ReturnAnalysis.multiple,
    _ => ReturnAnalysis.clear,
  };

  /// Pushes that arrive after the driver has left.
  List<ReturnNotice> get notices => switch (this) {
    ReturnScenario.multiple => const [
      ReturnNotice(
        body: '已確認車內整潔、補拍照片可判讀，您的信用分數維持不變，感謝配合✨',
        delay: Duration(seconds: 3),
      ),
    ],
    ReturnScenario.trash => const [
      ReturnNotice(
        body: '已確認車內整潔，您的信用分數維持不變，感謝配合✨',
        delay: Duration(seconds: 3),
      ),
    ],
